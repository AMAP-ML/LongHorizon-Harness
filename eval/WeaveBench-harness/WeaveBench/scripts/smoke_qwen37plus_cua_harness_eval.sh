#!/usr/bin/env bash
set -euo pipefail

if [ "$#" -ne 2 ]; then
  echo "usage: $0 <result_dir> <log_path>" >&2
  echo "       coordinate mode is automatic unless WEAVEBENCH_COMPUTER_COORD_MODE is set" >&2
  exit 2
fi

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

export WEAVEBENCH_NUM_ENVS="${WEAVEBENCH_NUM_ENVS:-1}"
export WEAVEBENCH_LIMIT="${WEAVEBENCH_LIMIT:-1}"

export CUA_HARNESS_MAX_ROUNDS="${CUA_HARNESS_MAX_ROUNDS:-1}"
export CUA_HARNESS_TASK_TIMEOUT_SECONDS="${CUA_HARNESS_TASK_TIMEOUT_SECONDS:-600}"
export CUA_HARNESS_GUI_TASK_TIMEOUT_SECONDS="${CUA_HARNESS_GUI_TASK_TIMEOUT_SECONDS:-$CUA_HARNESS_TASK_TIMEOUT_SECONDS}"
export CUA_HARNESS_CLI_TASK_TIMEOUT_SECONDS="${CUA_HARNESS_CLI_TASK_TIMEOUT_SECONDS:-$CUA_HARNESS_TASK_TIMEOUT_SECONDS}"
export CUA_HARNESS_ORCHESTRATOR_TIMEOUT_SECONDS="${CUA_HARNESS_ORCHESTRATOR_TIMEOUT_SECONDS:-180}"
export CUA_HARNESS_VERIFIER_TIMEOUT_SECONDS="${CUA_HARNESS_VERIFIER_TIMEOUT_SECONDS:-180}"

exec "$repo/scripts/run_qwen37plus_cua_harness_eval.sh" "$@"
